/**
 * Generate 24 data points for initial chart history
 */
export function generateInitialChartData(activeVerifiedCount: number): PriceTick[] {
  const points: PriceTick[] = [];
  const now = Date.now();
  const step = 60 * 1000; // 1 min steps

  // Baseline around current verified count
  let userCount = Math.max(1, activeVerifiedCount - 6);

  for (let i = 24; i >= 0; i--) {
    const time = now - i * step;
    const date = new Date(time);
    const timeLabel = date.toLocaleTimeString([], { hour: '2-digit', minute: '2-digit', second: '2-digit' });

    // Slight variance leading up to current activeVerifiedCount
    if (i > 0) {
      const delta = (Math.random() > 0.4 ? 1 : -1);
      userCount = Math.max(1, userCount + delta);
    } else {
      userCount = activeVerifiedCount;
    }

    const price = calculateDynamicPrice(userCount);
    points.push({
      timestamp: time,
      timeLabel,
      price,
      verifiedOnlineCount: userCount,
      volume: Math.floor(150000 + Math.random() * 450000),
    });
  }

  return points;
}
